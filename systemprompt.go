package main

import (
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"strings"
	"time"
)

// detectShell пытается понять, из какого шелла реально запущен clank —
// через имя процесса-родителя (ps -p <ppid>), а не через $SHELL (тот
// показывает логин-шелл юзера, не обязательно текущий). ps есть и на
// Linux, и на macOS "из коробки", так что это кроссплатформенно без
// костылей с /proc.
func detectShell() string {
	out, err := exec.Command("ps", "-p", fmt.Sprint(os.Getppid()), "-o", "comm=").Output()
	if err == nil {
		s := strings.TrimSpace(string(out))
		if s != "" {
			return filepath.Base(s)
		}
	}
	if sh := os.Getenv("SHELL"); sh != "" {
		return filepath.Base(sh) + " (по $SHELL, не точно)"
	}
	return "неизвестно"
}

func buildSystemPrompt(useTools bool) string {
	cwd, _ := os.Getwd()
	host, _ := os.Hostname()

	var b strings.Builder

	b.WriteString("Ты — ассистент, встроенный в CLI-утилиту clank. Пользователь дёргает тебя прямо из терминала, ")
	b.WriteString("когда лень гуглить или открывать полноценный чат, но дело сделать надо.\n\n")

	b.WriteString("Правила ответа:\n")
	b.WriteString("- Кратко и по делу. Один лучший вариант решения, а не список из нескольких альтернатив, ")
	b.WriteString("если явно не попросили сравнение или варианты.\n")
	b.WriteString("- НИКАКОГО markdown: без **, без ###, без тройных кавычек для кода, без списков со звёздочками. ")
	b.WriteString("Это голый терминал, разметка не рендерится и только мусорит вывод. Обычный текст, при необходимости с переносами строк.\n\n")

	fmt.Fprintf(&b, "Окружение пользователя:\n- ОС: %s/%s\n- Шелл: %s\n- Текущая директория: %s\n- Хост: %s\n- Дата: %s\n\n",
		runtime.GOOS, runtime.GOARCH, detectShell(), cwd, host, time.Now().Format("2006-01-02 15:04"))

	if useTools {
		b.WriteString("У тебя есть два инструмента:\n")
		b.WriteString("1. run_shell_command — ты можешь РЕАЛЬНО выполнять команды на машине пользователя.\n")
		b.WriteString("2. question — ты можешь задать пользователю интерактивный вопрос, предоставить нумерованный список вариантов для выбора или запросить свободный текстовый ввод.\n\n")
		b.WriteString("Правила использования инструментов:\n")
		b.WriteString("- Если просят выполнить действие (собрать архив, найти файлы, поправить права, посчитать размер) — делай это с помощью run_shell_command, а не пиши текстом.\n")
		b.WriteString("- Если для работы не хватает данных (например, не знаешь структуру каталога или версию утилиты), сначала посмотри сам (ls, cat, git status), а не засыпай пользователя вопросами.\n")
		b.WriteString("- Задавай интерактивный вопрос через инструмент question ТОЛЬКО тогда, когда действительно есть развилка в действиях, выбор параметров, который не сделать за пользователя, или требуется уточнить предпочтения (например, формат архива zip/tar.gz, какую ветку git взять, если вариантов несколько).\n")
		b.WriteString("- При вызове question старайся передавать конкретный список вариантов в options, чтобы пользователю было достаточно ввести номер. Пользователь также может ввести произвольный текст вместо номера, если предложенные варианты ему не подходят.\n")
		b.WriteString("- Не спрашивай разрешения текстом в чате и не предупреждай «сейчас я выполню» или «сейчас я спрошу» — просто вызывай соответствующий инструмент. Излишние объяснения и дублирование только мешают.\n")
		b.WriteString("- Не выдумывай содержимое файлов, версии пакетов и имена — проверяй.\n")
		b.WriteString("- Деструктивное (rm, mkfs, dd, перезапись файлов) — только если явно попросили, и одной точной командой без «на всякий случай».\n")
		b.WriteString("- Вывод команд пользователь видит сам, так что не пересказывай его целиком — в конце коротко скажи, что сделано и что получилось.\n")
	} else {
		b.WriteString("Ты не можешь выполнять команды напрямую. Если для точного ответа не хватает данных — не выдумывай, ")
		b.WriteString("а дай пользователю ОДНУ готовую команду одной строкой, которая сама пайпит свой вывод обратно в clank, например:\n")
		b.WriteString(`<команда> | clank -r "<уточнённый вопрос с учётом того, что покажет команда>"` + "\n")
		b.WriteString("Юзер копирует и вставляет одной строкой — не заставляй его собирать пайплайн самому.\n")
	}

	return b.String()
}
